def test_detection_prefers_the_most_specific_lockfile(tmp_path):
    (tmp_path / "requirements.txt").write_text("a==1\n")
    (tmp_path / "poetry.lock").write_text("")
    assert detect_lockfile(tmp_path).name == "poetry.lock"


def test_detection_walks_up_from_a_subdirectory(tmp_path):
    (tmp_path / "package-lock.json").write_text(json.dumps({"lockfileVersion": 3, "packages": {}}))
    nested = tmp_path / "src" / "components"
    nested.mkdir(parents=True)
    assert detect_lockfile(nested).name == "package-lock.json"


def test_detection_failure_is_actionable(tmp_path):
    with pytest.raises(NoLockfile) as info:
        detect_lockfile(tmp_path)
    message = str(info.value)
    assert "requirements.txt" in message
    assert "--lockfile" in message


def test_netbox_example_is_a_pinned_pypi_lockfile():
    inventory = parse_lockfile(EXAMPLES / "netbox-3.0" / "requirements.txt")
    assert inventory.ecosystem == "pypi"
    assert len(inventory.nodes) == 28
    assert all(node.version for node in inventory.nodes.values())


def test_plain_requirements_are_all_direct(tmp_path):
    """A hand-written requirements.txt declares its dependencies.

    There are no `# via` comments, so nothing in the file says "I was pulled in
    by something else".  Treating the whole file as transitive is not a
    cosmetic error: directness is what makes a package *critical*, so the
    effect is a mortality report where nothing is anyone's decision.  That
    happened to the NetBox demo and made its 27 critical dependencies
    disappear.
    """
    path = tmp_path / "requirements.txt"
    path.write_text(
        "# deploy pins\n"
        "Django==3.2.6\n"
        "django-filter==2.4.0\n"
        "pytest==7.0.0\n"
    )
    inventory = parse_lockfile(path)
    assert inventory.nodes["django@3.2.6"].dev is False
    assert "django@3.2.6" in inventory.direct
    assert "django-filter@2.4.0" in inventory.direct
    # A dev-tool pin is still not a critical dependency.
    assert "pytest@7.0.0" not in inventory.direct


def test_pip_compile_file_is_not_treated_as_all_direct(tmp_path):
    """The presence of `# via` switches on edge-based directness."""
    path = tmp_path / "requirements.txt"
    path.write_text(
        "django==3.2.6\n"
        "    # via -r requirements.in\n"
        "sqlparse==0.4.1\n"
        "    # via django\n"
    )
    inventory = parse_lockfile(path)
    assert inventory.direct == {"django@3.2.6"}
    assert len(inventory.nodes) == 2
