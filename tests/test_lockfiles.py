def test_pipfile_lock_is_flat_and_says_so(tmp_path):
    path = tmp_path / "Pipfile.lock"
    path.write_text(
        json.dumps(
            {
                "_meta": {},
                "default": {"requests": {"version": "==2.31.0"}},
                "develop": {"pytest": {"version": "==7.0.0"}},
            }
        )
    )
    inventory = parse_lockfile(path)
    assert inventory.nodes["requests@2.31.0"].version == "2.31.0"
    assert inventory.nodes["pytest@7.0.0"].dev
    assert any("does not record dependency edges" in w for w in inventory.warnings)


def test_yarn_lock_reads_pins_and_admits_it_cannot_build_edges(tmp_path):
    path = tmp_path / "yarn.lock"
    path.write_text(
        '# yarn lockfile v1\n\n"left-pad@^1.3.0":\n  version "1.3.0"\n'
        '  resolved "https://registry.example/left-pad-1.3.0.tgz"\n'
    )
    inventory = parse_lockfile(path)
    assert inventory.nodes["left-pad@1.3.0"].version == "1.3.0"
    assert any("does not build edges" in warning for warning in inventory.warnings)


