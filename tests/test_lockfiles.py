POETRY_LOCK = """
[[package]]
name = "django"
version = "4.2.0"
category = "main"
optional = false

[package.dependencies]
asgiref = ">=3.6.0,<4"
sqlparse = ">=0.3.1"

[[package]]
name = "asgiref"
version = "3.6.0"
category = "main"
optional = false

[[package]]
name = "sqlparse"
version = "0.4.4"
category = "main"
optional = false

[[package]]
name = "pytest"
version = "7.4.0"
category = "dev"
optional = false
"""


def test_poetry_lock_builds_real_edges(tmp_path):
    lock = tmp_path / "poetry.lock"
    lock.write_text(POETRY_LOCK)
    (tmp_path / "pyproject.toml").write_text(
        '[tool.poetry]\nname = "demo"\n'
        '[tool.poetry.dependencies]\npython = "^3.11"\ndjango = "^4.2"\n'
        '[tool.poetry.group.dev.dependencies]\npytest = "^7.4"\n'
    )
    inventory = parse_lockfile(lock)

    assert inventory.nodes["django@4.2.0"].version == "4.2.0"
    assert inventory.nodes["pytest@7.4.0"].dev
    assert inventory.direct == {"django@4.2.0"}

    edges = {(e.parent, e.child) for e in inventory.edges}
    assert ("django@4.2.0", "asgiref@3.6.0") in edges
    assert ("django@4.2.0", "sqlparse@0.4.4") in edges

    graph = analyse(inventory)
    assert graph.facts["django@4.2.0"].depth == 0
    assert graph.facts["asgiref@3.6.0"].depth == 1
    assert graph.facts["asgiref@3.6.0"].parents == ["django@4.2.0"]
    assert graph.facts["django@4.2.0"].critical
    assert not graph.facts["asgiref@3.6.0"].critical


def test_poetry_lock_without_pyproject_says_so(tmp_path):
    lock = tmp_path / "poetry.lock"
    lock.write_text(POETRY_LOCK)
    inventory = parse_lockfile(lock)
    assert any("pyproject.toml" in warning for warning in inventory.warnings)
    # Conservative fallback: every non-dev package is treated as direct.
    assert "django@4.2.0" in inventory.direct
    assert "pytest@7.4.0" not in inventory.direct


