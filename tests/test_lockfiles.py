def test_package_lock_v3_resolves_nested_node_modules(tmp_path):
    lock = tmp_path / "package-lock.json"
    lock.write_text(
        json.dumps(
            {
                "name": "demo",
                "lockfileVersion": 3,
                "packages": {
                    "": {"name": "demo", "dependencies": {"a": "^1.0.0"}, "devDependencies": {"b": "^1.0.0"}},
                    "node_modules/a": {"version": "1.0.0", "dependencies": {"c": "^1.0.0"}},
                    "node_modules/c": {"version": "2.0.0"},
                    "node_modules/a/node_modules/c": {"version": "1.5.0"},
                    "node_modules/b": {"version": "3.0.0", "dev": True},
                },
            }
        )
    )
    inventory = parse_lockfile(lock)
    assert inventory.ecosystem == "npm"
    assert inventory.nodes["b@3.0.0"].dev
    assert "a@1.0.0" in inventory.direct
    edges = {(e.parent, e.child) for e in inventory.edges}
    # npm resolution: `a`'s own copy of c shadows the hoisted one.
    assert ("a@1.0.0", "c@1.5.0") in edges


def test_package_lock_v1_nested_dependencies(tmp_path):
    lock = tmp_path / "package-lock.json"
    lock.write_text(
        json.dumps(
            {
                "name": "demo",
                "lockfileVersion": 1,
                "dependencies": {
                    "a": {"version": "1.0.0", "dependencies": {"c": {"version": "2.0.0"}}},
                    "b": {"version": "2.0.0", "dev": True},
                },
            }
        )
    )
    inventory = parse_lockfile(lock)
    assert inventory.nodes["a@1.0.0"].version == "1.0.0"
    assert inventory.nodes["b@2.0.0"].dev
    assert any(e.parent == "a@1.0.0" and e.child == "c@2.0.0" for e in inventory.edges)


