"""Lockfile parsing: six formats, one graph.

The interesting cases are the ones where a lockfile does *not* contain the
information a mortality report wants: Pipfile.lock has no edges, yarn.lock is
YAML, Cargo.lock does not mark direct dependencies.  In each case the parser
must degrade out loud (a warning in ``Inventory.warnings``) rather than invent
a tree.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from deadledger.errors import NoLockfile
from deadledger.graph import analyse
from deadledger.lockfiles import detect_lockfile, parse_lockfile

EXAMPLES = Path(__file__).parent.parent / "examples"


# ---------------------------------------------------------------------------
# requirements.txt
# ---------------------------------------------------------------------------


def test_requirements_parses_pins_and_markers(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text(
        "Django==3.2.6\n"
        "requests[security]==2.31.0 ; python_version >= '3.8'\n"
        "boto3>=1.0\n"
        "# a comment, not a dependency\n"
        "-r other.txt\n"
        "--index-url https://example.invalid/simple\n"
    )
    inventory = parse_lockfile(path)
    assert inventory.ecosystem == "pypi"
    assert inventory.nodes["django@3.2.6"].version == "3.2.6"
    assert inventory.nodes["requests@2.31.0"].extras == ("security",)
    # A range is not a pin: we keep the name but no version.
    assert inventory.nodes["boto3"].version is None
    assert len(inventory.nodes) == 3


def test_requirements_normalises_names_like_pypi(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text("Django_Filter==2.4.0\nzope.interface==5.0\n")
    inventory = parse_lockfile(path)
    assert "django-filter@2.4.0" in inventory.nodes
    assert "zope-interface@5.0" in inventory.nodes


def test_requirements_marks_dev_only_packages(tmp_path):
    path = tmp_path / "requirements.txt"
    path.write_text("django==3.2.6\npytest==7.0.0\npytest-cov==4.0.0\nblack==22.0.0\n")
    inventory = parse_lockfile(path)
    assert not inventory.nodes["django@3.2.6"].dev
    assert inventory.nodes["pytest@7.0.0"].dev
    assert inventory.nodes["pytest-cov@4.0.0"].dev
    assert inventory.nodes["black@22.0.0"].dev


def test_pip_compile_via_comments_mark_direct_dependencies(tmp_path):
    """pip-compile records direct deps as '# via -r requirements.in'."""
    path = tmp_path / "requirements.txt"
    path.write_text(
        "#\n"
        "# This file is autogenerated by pip-compile\n"
        "#\n"
        "django==3.2.6\n"
        "    # via -r requirements.in\n"
        "sqlparse==0.4.1\n"
        "    # via django\n"
    )
    inventory = parse_lockfile(path)
    assert "django@3.2.6" in inventory.direct
    assert "sqlparse@0.4.1" not in inventory.direct
    # And the edge from django -> sqlparse exists.  pip-compile names the
    # parent without a version, so the edge stores the bare name.
    assert any(
        edge.parent == "django" and edge.child == "sqlparse@0.4.1"
        for edge in inventory.edges
    )


