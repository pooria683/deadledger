def test_cargo_lock_excludes_the_workspace_crate_itself():
    inventory = parse_lockfile(EXAMPLES / "legacy-rust" / "Cargo.lock")
    assert "legacy-ingest@0.9.1" not in inventory.nodes
    assert inventory.nodes["tempdir@0.3.7"].version == "0.3.7"
    assert "tempdir@0.3.7" in inventory.direct
    # serde_json depends on serde, which makes serde depth 1 via that path.
    edges = {(e.parent, e.child) for e in inventory.edges}
    assert ("serde_json@1.0.68", "serde@1.0.130") in edges


def test_cargo_lock_without_manifest_warns(tmp_path):
    lock = tmp_path / "Cargo.lock"
    lock.write_text(
        '[[package]]\nname = "a"\nversion = "0.1.0"\ndependencies = ["b 0.2.0"]\n\n'
        '[[package]]\nname = "b"\nversion = "0.2.0"\n'
    )
    inventory = parse_lockfile(lock)
    assert any("Cargo.toml" in warning for warning in inventory.warnings)
    assert "a@0.1.0" in inventory.nodes


